using System.Security.Cryptography;

namespace Coil;

/// <summary>
/// The EC key pair Tesla requires for third-party applications: NIST P-256 (also known as
/// <c>secp256r1</c> / <c>prime256v1</c>). The public half is published for partner registration and
/// installed in vehicles as a Virtual Key; the private half signs Vehicle Command Protocol messages.
/// </summary>
/// <remarks>
/// <para>
/// Onboarding uses this key in three places, all of which must agree:
/// </para>
/// <list type="number">
///   <item><description>hosted at <c>https://&lt;domain&gt;/.well-known/appspecific/com.tesla.3p.public-key.pem</c> (see <see cref="WellKnownPublicKeyPath"/>),</description></item>
///   <item><description>registered with Tesla via <see cref="ITeslaPartnerClient.RegisterAsync"/>,</description></item>
///   <item><description>installed in the vehicle by the driver via the deep link <c>https://tesla.com/_ak/&lt;domain&gt;</c>.</description></item>
/// </list>
/// <para>
/// The PEM produced by <see cref="ExportPublicKeyPem"/> is a SubjectPublicKeyInfo document
/// (<c>-----BEGIN PUBLIC KEY-----</c>), byte-for-byte equivalent to what
/// <c>openssl ec -in key.pem -pubout</c> and Tesla's <c>tesla-keygen create</c> emit.
/// </para>
/// <para>
/// Verified against developer.tesla.com's partner-endpoint documentation on 2026-07-28; deviations
/// are recorded in <c>docs/api-deviations.md</c>.
/// </para>
/// </remarks>
public sealed class TeslaKeyPair : IDisposable
{
    /// <summary>
    /// The path, relative to the application domain's root, at which Tesla fetches the public key.
    /// </summary>
    public const string WellKnownPublicKeyPath = ".well-known/appspecific/com.tesla.3p.public-key.pem";

    private readonly ECDsa _key;

    private TeslaKeyPair(ECDsa key) => _key = key;

    /// <summary>
    /// The underlying key. Exposed for the Vehicle Command Protocol's ECDH handshake and signing;
    /// most callers only need the export methods.
    /// </summary>
    public ECDsa Key => _key;

    /// <summary>Generates a fresh P-256 key pair using the platform's secure RNG.</summary>
    public static TeslaKeyPair Generate() => new(ECDsa.Create(ECCurve.NamedCurves.nistP256));

    /// <summary>
    /// Loads a key pair from a PEM document. Accepts PKCS#8 (<c>BEGIN PRIVATE KEY</c>) and SEC 1
    /// (<c>BEGIN EC PRIVATE KEY</c>), so keys generated by <c>openssl ecparam -genkey</c> load as-is.
    /// </summary>
    /// <param name="pem">PEM-encoded private key.</param>
    /// <exception cref="ArgumentException">The PEM is malformed, or the key is not on the P-256 curve.</exception>
    public static TeslaKeyPair FromPrivateKeyPem(string pem)
    {
        var key = ECDsa.Create();
        try
        {
            key.ImportFromPem(pem);
        }
        catch (ArgumentException)
        {
            key.Dispose();
            throw;
        }
        catch (CryptographicException ex)
        {
            key.Dispose();
            throw new ArgumentException($"Not a readable PEM-encoded private key: {ex.Message}", nameof(pem), ex);
        }

        if (key.KeySize != 256)
        {
            var actualSize = key.KeySize;
            key.Dispose();
            throw new ArgumentException(
                $"Tesla requires a P-256 (secp256r1) key, but this key is {actualSize}-bit. " +
                "Regenerate it with `coil keys generate` or `openssl ecparam -name prime256v1 -genkey`.",
                nameof(pem));
        }

        return new TeslaKeyPair(key);
    }

    /// <summary>Exports the private key as an unencrypted PKCS#8 PEM (<c>BEGIN PRIVATE KEY</c>).</summary>
    /// <remarks>Treat the result as a secret: write it with owner-only permissions and never commit it.</remarks>
    public string ExportPrivateKeyPem() => WithTrailingNewline(_key.ExportPkcs8PrivateKeyPem());

    /// <summary>
    /// Exports the public key as a SubjectPublicKeyInfo PEM (<c>BEGIN PUBLIC KEY</c>) — the exact
    /// content to serve at <see cref="WellKnownPublicKeyPath"/>.
    /// </summary>
    public string ExportPublicKeyPem() => WithTrailingNewline(_key.ExportSubjectPublicKeyInfoPem());

    /// <summary>
    /// Appends the trailing newline that .NET's PEM writer omits but <c>openssl</c> and Go's
    /// <c>encoding/pem</c> (which Tesla's own tooling uses) both emit, so the published file is
    /// byte-for-byte what Tesla's fetcher normally sees. Always LF, never the platform separator —
    /// this content is served over HTTP, not written for a local editor.
    /// </summary>
    private static string WithTrailingNewline(string pem) => pem.EndsWith('\n') ? pem : pem + "\n";

    /// <summary>
    /// Exports the public key as a 65-byte uncompressed EC point (<c>0x04 || X || Y</c>).
    /// </summary>
    /// <remarks>
    /// This is the form Tesla's <c>partner_accounts/public_key</c> endpoint echoes back (hex-encoded),
    /// so it is what <see cref="ITeslaPartnerClient.GetPublicKeyAsync"/> results are compared against.
    /// It is also the wire format used by the Vehicle Command Protocol.
    /// </remarks>
    public byte[] ExportPublicKeyUncompressedPoint()
    {
        var parameters = _key.ExportParameters(includePrivateParameters: false);
        var x = parameters.Q.X ?? throw new InvalidOperationException("Key has no public X coordinate.");
        var y = parameters.Q.Y ?? throw new InvalidOperationException("Key has no public Y coordinate.");

        var point = new byte[1 + x.Length + y.Length];
        point[0] = 0x04; // uncompressed point marker
        x.CopyTo(point, 1);
        y.CopyTo(point, 1 + x.Length);
        return point;
    }

    /// <summary>
    /// The public key as a lower-case hex string of <see cref="ExportPublicKeyUncompressedPoint"/>,
    /// for comparing against what Tesla has on file.
    /// </summary>
    public string ExportPublicKeyHex() => Convert.ToHexString(ExportPublicKeyUncompressedPoint()).ToLowerInvariant();

    /// <inheritdoc />
    public void Dispose() => _key.Dispose();
}
